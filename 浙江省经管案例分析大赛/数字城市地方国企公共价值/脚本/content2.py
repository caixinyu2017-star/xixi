    "to policy-driven state-owned enterprises, reveals the dynamic feedback loop among its "
    "three dimensions, and offers an operational disaggregation of the authorization "
    "dimension. Practically, it argues that small and medium-sized cities should entrust "
    "digital pilots to state-owned vehicles integrating construction with operation, guard "
