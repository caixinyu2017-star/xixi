    "a twofold dilemma: fiscal and talent constraints prevent governments from independently "
    "leading city-level digital construction, while purely market-based actors lack the "
    "institutional obligation to serve public missions. Locally owned digital platform "
    "enterprises, jointly funded by municipal governments and central state-owned enterprises, "
    "represent an organizational innovation responding to this dilemma. Yet how such hybrid "
    "actors obtain legitimacy, convert policy resources into governance effectiveness, and "
    "translate value outputs back into expanded developmental conditions remains "
    "inadequately theorized.",

    "Taking Zhejiang Jiaxing Digital City Laboratory Co., Ltd. (hereafter Jiashu) as a single "
    "case, and drawing on Mark Moore's public value theory and its strategic triangle model, "
    "this study triangulates semi-structured interviews, archival materials and public policy "
    "documents to examine how a policy-driven local state-owned enterprise creates public value "
    "within a national digital-city pilot. The study identifies a three-dimensional pathway of "
    "authorization, empowerment and value appreciation: policy anchoring, government-enterprise "
    "co-construction and industry-university-research collaboration constitute the "
    "authorizing environment; technology platforms, data elements and high-level talent "
    "constitute operational capacity; and governance efficiency, inclusive public services and "
    "demonstration spillovers constitute public value.",

    "Three findings emerge. First, the three dimensions form a dynamic closed loop of "
    "authorization-empowerment-appreciation-feedback rather than a static triad: value output "
    "is not the terminus of the chain but the starting point of a new round of authorization, "
    "turning value creation from single-round consumption into self-reinforcing accumulation. "
    "Second, the authorizing environment can be disaggregated into three designable "
    "sub-dimensions—policy authorization, capital authorization and governance "
    "authorization—among which the separation of state ownership from central-SOE management "
    "is the pivotal arrangement reconciling public mission with technical professionalism, "
    "indicating that authorization is a constructible institutional instrument rather than an "
