def csv_copies(data, tr, va, te):
    """Plain-text copies of both tables, for anything that is not Excel."""
    import csv
    n, T, _ = data["X_raw"].shape
    X, mask, used = data["X_raw"], data["mask"], data["used"]
    split = np.empty(n, dtype=object)
    split[tr], split[va], split[te] = "train", "validation", "test"
    q = data["quest"]

    p1 = os.path.join(OUT, "participants.csv")
    with open(p1, "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.writer(fh)
        w.writerow(["participant_id", "split", "prompts_answered"]
                   + ["trait_" + s for s in D.FAM_SHORT]
                   + ["adapt_" + s for s in D.FAM_SHORT]
                   + ["label_" + s for s in D.FAM_SHORT]
                   + ["ERQ_reappraisal", "ERQ_suppression", "DERS_total"])
        for i in range(n):
            w.writerow([i + 1, split[i], int(mask[i].sum())]
                       + ["%.4f" % v for v in data["trait"][i]]
                       + ["%.4f" % v for v in data["adapt"][i]]
                       + [int(v) for v in data["Y"][i]]
                       + ["%.3f" % q["ERQ_reappraisal"][i],
                          "%.3f" % q["ERQ_suppression"][i],
                          "%.2f" % q["DERS_total"][i]])

    p2 = os.path.join(OUT, "episodes.csv")
    with open(p2, "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.writer(fh)
        w.writerow(["participant_id", "t_index", "day", "prompt_of_day",
                    "answered", "deployed_family"] + D.FEATURES)
        for i in range(n):
            for t in range(T):
                w.writerow([i + 1, t + 1, t // D.N_PROMPT + 1,
                            t % D.N_PROMPT + 1, int(mask[i, t]),
                            D.FAMILIES[int(used[i, t])]]
                           + ["%.4f" % v for v in X[i, t]])
    return p1, p2


