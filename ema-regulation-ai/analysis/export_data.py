# ---------------------------------------------------------------------------
def sheet(wb, title, rows, widths=None, freeze="A2", wrap_cols=()):
    """Write a list-of-lists to a new worksheet with a styled header."""
    ws = wb.create_sheet(title=title)
    for r in rows:
        ws.append(list(r))
    for c in range(1, len(rows[0]) + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill = HEAD_FILL
        cell.font = HEAD_FONT
        cell.alignment = Alignment(wrap_text=True, vertical="center")
    ws.freeze_panes = freeze
    if widths:
        for i, w in enumerate(widths, start=1):
            ws.column_dimensions[get_column_letter(i)].width = w
    for col in wrap_cols:
        for row in ws.iter_rows(min_row=2, min_col=col, max_col=col):
            for cell in row:
                cell.alignment = WRAP
    return ws


def note_sheet(wb, title, paragraphs, width=118):
    ws = wb.create_sheet(title=title)
    ws.column_dimensions["A"].width = width
    for i, p in enumerate(paragraphs, start=1):
        ws.cell(row=i, column=1, value=p).alignment = WRAP
        if p and not p.startswith(" ") and p.endswith("】"):
            ws.cell(row=i, column=1).font = Font(bold=True)
    return ws


def lag1(v):
    if len(v) < 3:
        return float("nan")
    return float(np.corrcoef(v[:-1], v[1:])[0, 1])


