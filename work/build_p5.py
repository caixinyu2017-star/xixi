h2(doc, "3.2  相对价值分级标签构建")
body(doc, "价值标签基于专利内在质量特征构造，采用熵权法客观确定指标权重以避免主观赋权的随意性。"
          "基于专利价值评价的经典多维框架，选取专利参考文献引用数、权利要求计数、"
          "发明人计数、同族专利成员数四项核心指标，"
          "分别对应技术影响力、法律保护范围、研发投入强度、市场布局广度四个价值维度。"
          "第 j 项指标的信息熵与熵权如式（1）所示，其中 n 为样本量、p_ij 为归一化后的指标值。")
add_equation(doc, r"e_{j}=-\frac{1}{\ln n}\sum_{i=1}^{n}p_{ij}\ln p_{ij},"
                  r"\quad w_{j}=\frac{1-e_{j}}{\sum_{k=1}^{m}(1-e_{k})}", 1)
body(doc, "专利综合价值得分为各指标归一化值的加权和，如式（2）所示，"
          "再通过自然间断点法划分为低、中、高三个价值等级，构建模型训练的基准标签[3]。")
add_equation(doc, r"S_{i}=\sum_{j=1}^{m}w_{j}\,z_{ij}", 2)
