h2(doc, "3.2  相对价值分级标签构建")
body(doc, "价值标签基于专利内在质量特征构造，并采用熵权法客观确定各指标权重。"
          "参照专利价值评价的经典多维框架，"
          "选取专利参考文献引用数、权利要求计数、发明人计数、同族专利成员数四项核心指标，"
          "分别对应技术影响力、法律保护范围、研发投入强度与市场布局广度四个价值维度。"
          "熵权法依据各指标取值的离散程度确定权重："
          "某一指标在样本间的差异越大，其携带的区分信息越多，所获权重也越高；"
          "反之，若某指标在绝大多数专利上取值接近，则其权重相应降低。"
          "这一做法可以避免主观赋权带来的随意性。"
          "需要说明的是，以引用数、权利要求数、同族规模等指标刻画专利价值，"
          "已被大量实证研究证明与专利的经济价值存在稳定相关^[5]，"
          "但相关并不等于等价，这也是第5.3节讨论的出发点。")
body(doc, "各指标加权合成后得到专利综合价值得分，再据此划分价值等级。"
          "对合成得分采用自然间断点法划分为低、中、高三个价值等级，"
          "作为模型训练的基准标签。"
          "需要说明的是，该标签是依据既定规则合成的相对价值等级，"
          "而非独立观测到的市场价值事实；"
          "模型的输出应理解为专利在该规则下的相对质量位次，"
          "这一性质对结果解读的影响将在第5.3节讨论。")

