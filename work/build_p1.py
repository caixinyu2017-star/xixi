h3(doc, "2.1.2  统一 Token 化与模态深度融合")
body(doc, "Qwen Omni 采用端到端原生全模态架构，把文本、图像、音频、视频四种模态统一转化为 Token 序列后"
          "输入同一 Transformer 骨干网络。视觉编码器采用 SigLIP2 架构，将图像帧与视频帧编码为视觉嵌入向量；"
          "音频编码器采用 AuT 架构，将音频波形转换为声学特征。多模态嵌入与文本 Token 在同一语义空间内"
          "相互注意，实现了模态融合而非简单拼接[4]。")
