h1(doc, "6  结论与展望")
body(doc, "本文的核心结论是：多模态大模型在专卖执法视频合规审核任务上已具备实用精度，"
          "但其价值的正确表达方式不是识别准确率，而是人机协同的工作量—查全率决策曲线。"
          "实验显示领域微调后的模型 F1 值达 91.9%，识别准确率随判定链条长度递减，"
          "跨模态联合判断类指标是后续优化的重点；"
          "而从部署决策看，人工复核量占全量 37.3% 时查全率即达 91.5%，"
          "为同等工作量下纯人工抽检的 2.45 倍，"
          "追求接近全查则需付出不成比例的人力，"
          "全生命周期成本测算给出的静态投资回收期约 1.37 年。")
body(doc, "本文的第二项结论是：此类系统落地的关键约束不在技术性能而在合规与正当性。"
          "数据边界、效力边界、用途边界三条原则，"
          "以及算法输出仅作线索提示、最终认定权保留于法制审核人员的人在回路机制，"
          "是系统能够长期稳定运行的制度前提；"
          "同时，全量监督可能诱发的目标替代行为需要通过反向监测指标与激励相容设计予以防范，"
          "这一点在既有研究中普遍缺失，却直接决定方案的可持续性。")
body(doc, "后续研究可从四个方向推进。"
          "一是补做同架构零样本对照组与标注一致性检验，完善实验设计的内部效度，这两项无法由外部推算。"
          "二是向实时辅助执法延伸，在执法终端部署轻量级模型，实现事前预警、事中纠偏。"
          "三是扩展视频语义理解范畴，从程序合规检验转向涉案物品识别、经营状况分析与冲突风险预判。"
          "四是推进多源数据融合，把视频数据与案件、信用、举报、物流数据关联，强化精准打击的情报支撑。"
          "在推进上述方向的同时，应同步建立算法影响评估与定期审计机制，"
          "使技术能力的扩展始终处于治理框架之内。")

