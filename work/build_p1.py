h2(doc, "6.1  数据安全与个人信息保护")
body(doc, "执法记录仪视频属于含有敏感个人信息的数据，其处理必须守住合规底线。"
          "视频中同时包含执法人员与行政相对人的人脸、声纹信息，"
          "《中华人民共和国个人信息保护法》对公共场所图像采集设备的安装、"
          "以及敏感个人信息的处理均设有专门规则^[5]。"
          "据此，系统在三个方面作了限定："
          "一是本地化处理，模型以私有化方式部署于省局政务云环境，"
          "原始音视频不出政务云边界，不调用公网大模型接口，"
          "这也是本研究选择可私有部署的开源模型而非直接调用商用服务的主要原因；"
          "二是最小必要，推理前对与合规判定无关的人脸区域作去标识化处理，"
          "分析报告中涉及行政相对人姓名、许可证号等信息的在归档与展示环节作脱敏；"
          "三是分级授权与审计留痕，视频原件、分析报告、统计结果对应不同访问权限，"
          "所有调阅行为记录操作人、时间与事由并留存日志^[6]。")

h2(doc, "6.2  算法结论的效力边界")
body(doc, "算法输出应当定位为“线索提示”而非“认定结论”，最终认定权必须保留于法制审核人员。"
          "作出这一限定有三方面理由："
          "其一，模型对部分指标的识别准确率尚在 88%～96% 区间，误报不可避免，"
          "直接据以追责将造成对合规执法行为的误伤；"
          "其二，执法程序的合规性判断包含情境因素，"
          "例如现场存在安全风险时执法人员调整取证顺序属于合理裁量，模型难以识别；"
          "其三，行政相对人与执法人员对算法结论均应享有异议权，"
          "这是人机协作系统设计的基本准则^[7]。"
          "据此，系统建立了“机器初筛—人工复核—异议申诉—反馈迭代”的闭环，"
          "执法人员对认定结果有异议的可通过申诉通道提出，"
          "申诉结论一并进入标注库用于模型迭代。")

h2(doc, "6.3  防止“重痕迹、轻实效”的考核导向")
body(doc, "全量监督一旦与考核简单挂钩，就可能诱发“镜头合规而实质不合规”的行为，这一风险需要事先防范。"
          "当被监督者知晓监督规则时，理性反应可能是把注意力放在满足检测项上，"
          "表现为刻意对镜头完成亮证动作而实质沟通不充分、在关键环节走出取景范围等。"
          "此类行为会使监督数据虚假向好，反而掩盖真实风险。"
          "为此建议在制度设计上作三项安排："
          "一是设置反向监测指标，对视频时长异常缩短、镜头长时间遮挡等情况单独监测，"
          "指标异常本身即触发人工核查；"
          "二是采用“首违提示、整改闭环”而非直接扣分，"
          "首次发现的程序瑕疵仅推送提示并跟踪整改，重复发生方进入考核；"
          "三是把分析结果的主要用途放在培训改进上——"
          "若某一环节的瑕疵率在全局普遍偏高，首先应检讨的是规范表述是否清晰、流程设计是否可行，"
          "而不是追究个人责任。")

