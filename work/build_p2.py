h2(doc, "2.1  穿透式监管的概念转换")
body(doc, "穿透式监管源于金融监管实践，其原义是穿透名义持有人识别底层资产与实际控制人，"
          "解决的是法律形式与经济实质相分离的问题[12]。"
          "烟草行业的内部监督并不存在“名实分离”的结构，直接平移会使概念空转。"
          "因此，把该范式引入行业监督之前，必须完成一次显式的概念转换。")
body(doc, "本文认为，在国有垂直管理体制下，与金融领域“形式与实质分离”相对应的问题，"
          "是**监督信息沿委托代理链条的层层损耗**。"
          "国家局—省局—市局—县局构成一条四级委托代理链，"
          "每一级代理人既是上级的监督对象，又是下级的监督主体；"
          "信息在逐级上报中被选择性过滤，监督指令在逐级下达中被稀释，"
          "最终形成“上热、中温、下冷”的梯度格局。"
          "据此，穿透式监督的实质可以重新表述为：**在既有的逐级代理链之外，"
          "新增一条不随层级衰减的直达通道**。"
          "这一表述带来一个可测量的定义——穿透度等于直达通道所覆盖的业务事项占全部业务事项的比例，"
          "从而使“穿透”从修辞转变为可以计算、可以考核的变量。")

