h1(doc, "7  结论")
body(doc, "本文对穿透式监管视角下的烟草行业大监督体系做了三方面推进。")
body(doc, "第一，完成了概念转换。在国有垂直管理体制下，“穿透”对应的是监督信息沿委托代理链条的层层损耗；"
          "穿透式监督的实质是在逐级代理链之外新增一条不随层级衰减的直达通道，"
          "其程度可由直达通道覆盖的业务事项比例来测量。"
          "这使“穿透”从修辞转变为可计算、可考核的变量。")
body(doc, "第二，把成因分析从认识层面推进到结构与成本层面。"
          "数值分析显示，中等衰减情形下县级局监督效力仅为国家局的 34.3%，"
          "直达通道覆盖 60% 可使其回升至 67.7%；"
          "同时，忽略基层负担这一成本项将使最优监督强度被高估 61.0%。"
          "后一结论提示，监督设计必须把“减负”作为内生约束而非事后补救。")
body(doc, "第三，给出了可执行的优先级、路线与验证方案。"
          "边际贡献仿真确定的实施优先级为数据穿透 > 制度穿透 > 流程穿透 > 责任穿透，"
          "据此形成三阶段路线与责任分工；"
          "监督效能评价指标体系的组合赋权通过一致性检验；"
          "功效分析则明确了评估单元必须下沉至稽查中队或业务事项层级，"
          "否则准实验评估不具备统计功效。")
body(doc, "本文的局限在于，各项数值结果均基于参数化模型的情景分析，"
          "参数取值虽有依据并配有敏感性分析，但仍需真实数据校准。"
          "后续研究应采集本单位的监督事项台账、基层填报工时与监督效能评分数据，"
          "对衰减率、过载系数与各维成熟度做实证估计，"
          "在此基础上重跑上述模型，形成本地化的决策依据。")

