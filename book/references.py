def _norm(it):
    # 将 "桂琦寒等（2006）" 规范为 "桂琦寒等，2006"（作者，年），c() 再统一加外括号
    return it.replace('（', '，').replace('）', '')


REFS = {k: {'intext': _norm(it), 'gb': gb} for k, it, gb in _DATA}

_ORDER = []


def c(key, paren=True, prefix='', suffix=''):
    """登记并返回文中引用串。paren=False 用于句法嵌入（如"…如 X（年）所示"）。"""
    if key not in REFS:
        raise KeyError(f'未知文献 key: {key}')
    if key not in _ORDER:
        _ORDER.append(key)
    it = REFS[key]['intext']
    body = f'{prefix}{it}{suffix}'
    return f'（{body}）' if paren else body


def cc(*keys):
    """多篇合并引用：（作者1，年；作者2，年）"""
    parts = []
    for k in keys:
        if k not in _ORDER:
            _ORDER.append(k)
        parts.append(REFS[k]['intext'])
    return '（' + '；'.join(parts) + '）'


def gb_ordered():
    """按首次引用顺序返回 GB 著录列表。未被引用者追加在末尾（保证完整）。"""
    used = list(_ORDER)
    rest = [k for k in REFS if k not in _ORDER]
    return [REFS[k]['gb'] for k in used + rest]


def n_used():
    return len(_ORDER)


def reset():
    _ORDER.clear()
