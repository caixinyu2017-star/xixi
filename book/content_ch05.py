def _numi_region_table():
    reg = R['numi_by_region']
    years = ['2006', '2010', '2015', '2020', '2023']
    header = ['地区'] + [f'{y}年' for y in years] + ['年均增长(%)']
    rows = []
    for name in ['东部', '中部', '西部', '东北']:
        vals = [reg[name][y] for y in years]
        g = ((vals[-1] / vals[0]) ** (1 / 17) - 1) * 100
        rows.append([name] + [f'{v:.3f}' for v in vals] + [f'{g:.2f}'])
    nat = R['numi_national']
    natvals = [nat[y] for y in years]
    gn = ((natvals[-1] / natvals[0]) ** (1 / 17) - 1) * 100
    rows.append(['全国'] + [f'{v:.3f}' for v in natvals] + [f'{gn:.2f}'])
    return header, rows


