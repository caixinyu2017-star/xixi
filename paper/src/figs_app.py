import json, os, colorsys
import numpy as np
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle, Wedge, Circle

BASE="/tmp/claude-0/-home-user-xixi/013086be-932a-56cd-b187-9ec3125f6bc6/scratchpad"
DATA=os.path.join(BASE,"data"); FIG=os.path.join(BASE,"figs")
plt.rcParams.update({"font.family":"serif","font.serif":["DejaVu Serif","Liberation Serif"],
    "font.size":11,"savefig.dpi":320,"axes.grid":True,"grid.alpha":0.3})
H=json.load(open(os.path.join(DATA,"harmony.json")))
L=json.load(open(os.path.join(DATA,"layout.json")))
PALETTE=plt.cm.tab20(np.linspace(0,1,20))
