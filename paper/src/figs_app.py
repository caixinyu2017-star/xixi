# ---------- Fig 11: palettes + hue wheel ----------
K="7"
showalgos=["MSSBOA","LSHADE","SBOA","GWO"]
fig=plt.figure(figsize=(12,4.6))
gs=fig.add_gridspec(1,2,width_ratios=[1,1.7],wspace=0.18)
# (a) hue wheel with MSSBOA palette + best-fit template sector (illustrative X template)
axw=fig.add_subplot(gs[0,0],projection='polar'); axw.set_theta_zero_location("E"); axw.set_theta_direction(1)
for ang in range(0,360,2):
    axw.bar(np.radians(ang),1.0,width=np.radians(2.2),bottom=0.8,
            color=colorsys.hsv_to_rgb(ang/360,0.85,0.95),edgecolor="none")
# template X: two 94 deg sectors opposite, illustrative rotation
import numpy as _np
for c in (40,220):
    axw.bar(np.radians(c),0.55,width=np.radians(93.6),bottom=0.0,color=(0.6,0.6,0.6,0.35),edgecolor="none")
pal=H["palettes"][K]["MSSBOA"]
for i,(r,g,b) in enumerate(pal):
    h,s,v=colorsys.rgb_to_hsv(r,g,b)
    axw.plot(np.radians(h*360),0.5,'o',ms=12,color=(r,g,b),mec='k',mew=0.8)
axw.set_yticklabels([]); axw.set_xticklabels([]); axw.set_title("(a) MSSBOA palette on the hue wheel\n(gray = best-fit harmonic template)",fontsize=9)
axw.grid(False)
# (b) palette strips
axp=fig.add_subplot(gs[0,1]); axp.set_xlim(0,1); axp.set_ylim(0,len(showalgos)); axp.axis("off")
