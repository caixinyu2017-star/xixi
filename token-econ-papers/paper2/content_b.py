MINUS = '−'          # U+2212，负号一律用它


def n(x, d=4):
    """数值转字符串，负号用 U+2212。"""
    s = f'{abs(float(x)):.{d}f}'
    return (MINUS + s) if float(x) < 0 else s


def pp(x, d=2):
    """比例转百分点字符串（取绝对值）。"""
    return f'{abs(float(x)) * 100:.{d}f}'


def dd(v, k):
    return D[v][k]


def drow(label, unit, v, d=4):
    return [label, unit] + [n(dd(v, k), d) for k in ('mean', 'sd', 'p25', 'p50', 'p75')]


def ym(m):
    """把 2024-11 写成 2024年11月。"""
    y, mo = m.split('-')
    return f'{y}年{int(mo)}月'


def cohort_n(arm):
    return sum(SP['cohorts'][arm].values())


def cohort_batches(arm):
    return len(SP['cohorts'][arm])


def first_month(arm):
    return sorted(SP['cohorts'][arm])[0]


def named(arm, city):
    return ym(SP['named_cities'][arm][city])


def n_named():
    """有公开处理时点记录、因而使用真实城市名的城市数。"""
    s = set()
    for arm in ('A1', 'A2', 'B'):
        s |= set(SP['named_cities'][arm])
    return len(s)


def pre_month():
    """事前期的最后一个月份标签（首个平台上线月的前一个月）。"""
    ms = FIG['months']
    return ms[ms.index(first_month('A1')) - 1]


def pretrend_all():
    """全部事件研究事前联合检验的组数与最小 p 值。"""
    ps = [EV[y][arm]['pretrend_joint']['p']
          for y in EV for arm in ('A1', 'A2', 'B')]
    return len(ps), min(ps)


