def n(x, d=4):
    """定点数字符串，负号用 U+2212。"""
    s = f'{abs(x):.{d}f}'
    return (MINUS + s) if x < 0 else s


def pp(x, d=2):
    """把系数写成百分点（取绝对值，方向由行文交代）。"""
    return f'{abs(x) * 100:.{d}f}'


def mag(x, d=4):
    """系数的绝对值（用于“下降／上升××”这类已由行文交代方向的表述）。"""
    return f'{abs(x):.{d}f}'


