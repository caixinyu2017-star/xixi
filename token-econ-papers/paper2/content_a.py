def n(x, d=4):
    """定点数字符串，负号用 U+2212。"""
    s = f'{abs(x):.{d}f}'
    return (MINUS + s) if x < 0 else s


def pp(x, d=2):
    """把系数写成百分点（取绝对值，方向由行文交代）。"""
