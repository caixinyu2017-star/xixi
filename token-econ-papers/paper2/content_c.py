def n(x, d=4):
    """数值转字符串，负号用 U+2212。"""
    x = float(x)
    s = f'{abs(x):.{d}f}'
    return (MINUS + s) if x < 0 else s


def mag(x, d=4):
    """系数的绝对值（方向由行文交代）。"""
    return f'{abs(float(x)):.{d}f}'


def pp(x, d=2):
    """把系数写成百分点（取绝对值）。"""
    return f'{abs(float(x)) * 100:.{d}f}'


def rel(x, base, d=1):
    """系数相对于样本均值的百分比（取绝对值）。"""
    return f'{abs(float(x) / float(base)) * 100:.{d}f}'


def lnpct(x, d=1):
    """对数点折算为百分比变化（取绝对值）。"""
    return f'{abs(exp(float(x)) - 1.0) * 100:.{d}f}'


def star(p):
    p = float(p)
    return '***' if p < 0.01 else ('**' if p < 0.05 else ('*' if p < 0.1 else ''))


def pv(p, d=3):
    p = float(p)
    return '＜0.001' if p < 0.001 else f'{p:.{d}f}'


def cell(r, d=4):
    """系数（星号）＋换行＋括号内标准误。"""
    return f'{n(r["coef"], d)}{star(r["p"])}\n({float(r["se"]):.{d}f})'


def zcell(r, d=4):
    """差异行：系数＋方括号内 z 值。"""
    return f'{n(r["coef"], d)}{star(r["p"])}\n[z＝{n(r["z"], 2)}]'


