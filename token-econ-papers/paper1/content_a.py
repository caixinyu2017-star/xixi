def n(x, d=3):
    """定点数字符串，负号用 U+2212。"""
    s = f'{abs(x):.{d}f}'
    return (MINUS + s) if x < 0 else s


def pc(x, d=1):
    """把百分数值取绝对值后写成字符串（方向由行文交代）。"""
    return f'{abs(x):.{d}f}'


