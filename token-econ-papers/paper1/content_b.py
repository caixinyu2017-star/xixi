def n(x, d=4):
    """数值转字符串，负号用 U+2212。"""
    s = f'{abs(float(x)):.{d}f}'
    return (MINUS + s) if float(x) < 0 else s


def pc(x, d=1, signed=False):
    """百分数（输入已是百分点）。"""
    s = f'{abs(float(x)):.{d}f}%'
    if float(x) < 0:
        return MINUS + s
    return ('+' + s) if signed else s


def star(p):
    return '***' if p < 0.01 else ('**' if p < 0.05 else ('*' if p < 0.1 else ''))


def cell(c, se, p, d=4):
    return f'{n(c, d)}{star(p)}\n({se:.{d}f})'


def hb(eq, v, k='coef'):
    return HED[eq]['beta'][v][k]


def hcell(eq, v):
    b = HED[eq]['beta'][v]
    return cell(b['coef'], b['se'], b['p'])


def dsc(panel, v, k):
    return (DA if panel == 'A' else DB)[v][k]


def drow(panel, label, unit, v, d=4):
    s = dsc(panel, v, 'mean'), dsc(panel, v, 'sd'), dsc(panel, v, 'min'), dsc(panel, v, 'max')
    return [label, unit] + [n(x, d) for x in s]


def ym(m):
    """把 2023-01 写成 2023年1月。"""
    y, mo = m.split('-')
    return f'{y}年{int(mo)}月'


def lv(name, month):
    """指数序列在某月的水平。"""
    return IDX[name][MON.index(month)]


def tier_drop(tier, m0='2023-01', m1='2026-06'):
    """某档位均价从 m0 到 m1 的累计变化（百分点）。"""
    s = TIER['table'][tier]
    i0, i1 = TIER['months'].index(m0), TIER['months'].index(m1)
    return 100.0 * (s[i1] / s[i0] - 1.0)


