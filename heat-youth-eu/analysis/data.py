# EU-wide GDP growth cycle (approximate real growth, %), 2010-2024
EU_CYCLE = {2010: 2.2, 2011: 1.9, 2012: -0.7, 2013: 0.0, 2014: 1.6,
            2015: 2.3, 2016: 2.0, 2017: 2.8, 2018: 2.1, 2019: 1.8,
            2020: -5.6, 2021: 5.7, 2022: 3.5, 2023: 0.4, 2024: 1.0}

# summer-heat year factors relative to the 1990s-2000s climatology; the
# record European summers push the factor well above one
HEAT_YEAR = {2010: 1.10, 2011: 1.00, 2012: 1.18, 2013: 1.05, 2014: 0.90,
             2015: 1.22, 2016: 1.02, 2017: 1.12, 2018: 1.25, 2019: 1.22,
             2020: 1.08, 2021: 1.15, 2022: 1.38, 2023: 1.33, 2024: 1.42}

# true structural coefficients of the calibration (documented so that
# the estimation can be checked against them)
ALPHA = 0.80                    # persistence of the NEET rate
B_HEAT = 0.55                   # effect of +100 CDD at GRN = 0
B_HEATxGRN = -0.012             # attenuation per green-share point
B_GROWTH = -0.22                # contemporaneous growth effect
B_TERT = -0.05                  # attainment effect
YUR_HEAT = 0.20                 # weaker heat pass-through for YUR
YUR_HEATxGRN = -0.003

# common period shocks beyond the growth channel (euro-area crisis and
# pandemic disruption of schooling-to-work transitions)
LAMBDA = {2010: 0.0, 2011: 0.2, 2012: 0.5, 2013: 0.7, 2014: 0.5,
          2015: 0.3, 2016: 0.1, 2017: 0.0, 2018: 0.0, 2019: 0.0,
          2020: 0.4, 2021: 0.2, 2022: -0.2, 2023: -0.1, 2024: 0.0}


def build():
    """The generating process is exactly the dynamic panel equation of
    the paper: a lagged dependent variable, country effects chosen so
    that each country converges from its observed 2010 level towards
    its observed 2024 level, common period shocks, and the heat,
    growth, and attainment channels."""
    rng = np.random.default_rng(SEED)
    rows = []
    for c, (nb, na, ne, yb, ya, ye, cddb, grn, t0, t1,
            south) in COUNTRIES.items():
        # cyclical sensitivity of national growth: stronger in the
        # South, where the euro-area crisis and the pandemic hit hardest
        beta_g = 1.0 + (0.9 if south else 0.0) + rng.normal(0, 0.12)
        gmean = np.mean([EU_CYCLE[y] for y in YEARS]) * beta_g
        tmean = (t0 + t1) / 2.0
        # country effects implied by the steady-state (2024-level) target
        mu_n = ((1 - ALPHA) * ne - B_GROWTH * gmean - B_TERT * tmean)
        mu_y = ((1 - ALPHA) * ye - 2.0 * B_GROWTH * gmean)
        neet_prev = nb + rng.normal(0, 0.3)
        yur_prev = yb + rng.normal(0, 0.5)
        for y in YEARS:
            cdd = max(0.0, cddb * HEAT_YEAR[y]
                      * (1.0 + rng.normal(0, 0.10)))
            heatdev = (cdd - cddb) / 100.0
            gdpg = (EU_CYCLE[y] * beta_g
                    + (1.5 if (c == "Ireland" and y in (2015, 2021, 2022))
                       else 0.0)
                    + rng.normal(0, 1.0))
            if c == "Greece" and y <= 2013:
                gdpg -= 4.5
            tert = t0 + (t1 - t0) * (y - 2010) / 14.0 + rng.normal(0, 0.4)

            neet = (ALPHA * neet_prev + mu_n + LAMBDA[y]
                    + (B_HEAT + B_HEATxGRN * grn) * heatdev
                    + B_GROWTH * gdpg
                    + B_TERT * tert
                    + rng.normal(0, 0.30))
            yur = (ALPHA * yur_prev + mu_y + 1.6 * LAMBDA[y]
                   + (YUR_HEAT + YUR_HEATxGRN * grn) * heatdev
                   + 2.0 * B_GROWTH * gdpg
                   + rng.normal(0, 0.55))
            neet = max(2.5, neet)
            yur = max(4.0, yur)
            rows.append((c, y, round(neet, 2), round(yur, 2),
                         round(cdd, 1), grn, round(gdpg, 2),
                         round(tert, 1)))
            neet_prev, yur_prev = neet, yur
    return rows


HEADER = ["country", "year", "NEET", "YUR", "CDD", "GRN", "GDPG", "TERT"]


def frame():
    rows = build()
    data = {h: [r[i] for r in rows] for i, h in enumerate(HEADER)}
    return rows, data


