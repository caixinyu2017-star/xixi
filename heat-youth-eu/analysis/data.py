"""The EU-27 balanced country-year panel, 2010-2024.

The panel is generated by a documented, seeded calibration that follows
the published Eurostat trajectories of each series (the euro-area crisis
peak of youth disengagement around 2013, the long recovery to 2019, the
COVID-19 bump of 2020-2021, the subsequent decline; the exceptionally
hot European summers of 2012, 2015, 2018, 2019, 2022, 2023 and 2024;
the pandemic collapse and rebound of GDP growth; the steady rise of
tertiary attainment). Level calibrations per country are the
author-model's best-effort readings of the published series. The README
carries the data-provenance disclosure and the instruction to replace
this generator with a genuine Eurostat extraction before submission.

Variables
---------
NEET   Young people neither in employment nor in education and
       training, % of the population aged 15-29 (edat_lfse_20).
YUR    Youth unemployment rate, % of the labour force aged 15-24
       (une_rt_a); used in the sensitivity analysis.
CDD    Cooling degree days (nrg_chdd_a), annual, country level.
GRN    Share of green infrastructure (green urban areas and urban
       forest) in the functional urban areas of the country, %,
       time-invariant endowment compiled from the Copernicus Urban
       Atlas land-monitoring products.
GDPG   Real GDP growth rate, % (tec00115).
TERT   Tertiary educational attainment, % of the population aged
       25-34 (edat_lfse_03).
"""
