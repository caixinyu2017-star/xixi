    _t, _b, _a = [
        ('G　Goal　这次想解决什么',
         '「这 20 分钟，你最想理清哪一件事？」「解决到什么程度，你会觉得这次谈得值？」'
         '——先收窄。谈三件事等于一件也没谈。', GREEN),
        ('R　Reality　现在到底是什么情况',
         '「这家客户目前推进到哪一环了？」「你上一次跟他联系是什么时候、他说了什么原话？」'
         '——只问事实，不问感觉。多数卡点在这一步就浮出来了。', BLUE),
        ('O　Options　还有哪些做法',
         '「如果不能降价，你还能给他什么？」「换成是老李，他会先找谁？」'
         '——至少逼出三个选项。只有一个选项时，人是没有选择感的，也就没有承诺感。', ORANGE),
        ('W　Will　你打算做哪一个、什么时候',
         '「这三个里你先做哪个？」「具体哪一天？需要我做什么？」'
         '——必须由他说出口、并且落到日期。这一步一含糊，前面三步全白谈。', RED)][_i]
