def star(p):
    return '***' if p < 0.01 else ('**' if p < 0.05 else ('*' if p < 0.1 else ''))


def cell(coef, se, p, d=4):
    return f'{coef:.{d}f}{star(p)}\n({se:.{d}f})'


def bcell(y, spec='full', d=4):
    r = B[y][spec]
    return cell(r['coef']['post'], r['se']['post'], r['p']['post'], d)


def pp(x, d=2):
    return f'{abs(x) * 100:.{d}f}'


