REFS = {k: {'intext': it, 'gb': gb} for k, it, gb in _DATA}
_ORDER = []


def c(key, paren=True, prefix='', suffix=''):
    """登记并返回文中引用串。paren=False 用于句法嵌入。"""
    if key not in REFS:
        raise KeyError(f'未知文献 key: {key}')
    if key not in _ORDER:
        _ORDER.append(key)
    it = REFS[key]['intext']
    body = f'{prefix}{it}{suffix}'
    return f'（{body}）' if paren else body


def cc(*keys):
    """多篇合引：按发表年份从先到后排序（同年保持传入顺序）。"""
    import re as _re
    for k in keys:
        if k not in REFS:
            raise KeyError(f'未知文献 key: {k}')
        if k not in _ORDER:
            _ORDER.append(k)

    def _year(k):
        m = _re.search(r'(\d{4})', REFS[k]['intext'])
        return int(m.group(1)) if m else 9999

    ordered = sorted(keys, key=_year)
    return '（' + '；'.join(REFS[k]['intext'] for k in ordered) + '）'


def gb_ordered():
    used = list(_ORDER)
    rest = [k for k in REFS if k not in _ORDER]
    return [REFS[k]['gb'] for k in used + rest]


def n_used():
    return len(_ORDER)


def reset():
    _ORDER.clear()
